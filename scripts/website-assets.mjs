import { readdir, writeFile } from "node:fs/promises";
import { relative, resolve, sep } from "node:path";
const root = resolve("public");
async function collect(folder) {
  const result = [];
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    const path = resolve(folder, entry.name);
    if (entry.isDirectory()) result.push(...await collect(path));
    else if (entry.isFile() && /\.(png|jpe?g|webp)$/i.test(entry.name)) result.push("/" + relative(root, path).split(sep).join("/"));
  }
  return result;
}
const paths = (await collect(root)).sort();
await writeFile("src/features/public/websiteAssets.generated.ts", "// Generated by scripts/website-assets.mjs from public raster assets.\nexport const websiteAssets: readonly string[] = " + JSON.stringify(paths, null, 2) + ";\n");
console.log(`Public raster asset manifest: ${paths.length} paths`);
